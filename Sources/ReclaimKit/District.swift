import Foundation

/// What a tile is built as on the city map.
///
/// The map is drawn as a town: every tile is a city block whose area is its
/// share of the folder, and what stands on the block says what is in it. Most
/// districts follow the file family, so the colour legend still reads the same.
/// `landfill` is the exception: it marks things that are rebuilt on demand —
/// caches, build output, logs, used installers — so they stand out as the
/// obvious place to look first. It is a hint, never an action: removing
/// anything is still the user's call.
public enum District: String, CaseIterable, Codable, Sendable {
    case techCampus, dataCenter, school, stadium, park, warehouse, factory, utility, housing, landfill

    public var label: String {
        switch self {
        case .techCampus: return "Tech campus"
        case .dataCenter: return "Data centre"
        case .school: return "School"
        case .stadium: return "Stadium"
        case .park: return "Park"
        case .warehouse: return "Warehouse"
        case .factory: return "Factory"
        case .utility: return "Utility works"
        case .housing: return "Housing"
        case .landfill: return "Landfill"
        }
    }

    /// The district a family is zoned as, when nothing marks it as landfill.
    public static func zoned(_ family: FileFamily) -> District {
        switch family {
        case .code: return .techCampus
        case .data: return .dataCenter
        case .document: return .school
        case .media: return .stadium
        case .image: return .park
        case .archive: return .warehouse
        case .app: return .factory
        case .system: return .utility
        case .other: return .housing
        }
    }

    /// Folder names whose contents are regenerated by whatever made them.
    /// Lowercased; matched against the whole name, never a substring, so a
    /// folder called "Cache Valley Photos" is not mistaken for one.
    static let reclaimableFolders: Set<String> = [
        "caches", "cache", ".cache", "__pycache__", ".pytest_cache", ".mypy_cache",
        "deriveddata", "node_modules", ".build", ".gradle", ".npm", ".yarn",
        "logs", "tmp", "temp", ".tmp", ".trash", "ios devicesupport",
        "watchos devicesupport", "xcode previews",
    ]

    /// Files that are only ever leftovers: logs, temp files, Finder metadata,
    /// and disk images and installer packages, which have done their job once
    /// the app they carried is installed.
    static let reclaimableExtensions: Set<String> = [
        "log", "tmp", "dmg", "pkg", "crash", "ips",
    ]

    /// Whether `name` on its own marks something as rebuildable. `ext` is the
    /// lowercased extension, or "" for a directory.
    public static func isReclaimable(name: String, isDirectory: Bool, ext: String) -> Bool {
        if isDirectory {
            // Cheap reject before lowercasing: every listed name is short.
            guard name.utf8.count <= 24 else { return false }
            return reclaimableFolders.contains(name.lowercased())
        }
        if reclaimableExtensions.contains(ext) { return true }
        return name.utf8.count == 9 && name.lowercased() == ".ds_store"
    }

    /// The district for one tile.
    ///
    /// `insideReclaimable` is true when a folder above the tile is itself
    /// rebuildable: everything inside `~/Library/Caches` is landfill, whatever
    /// the individual folders there happen to be called.
    public static func of(name: String, isDirectory: Bool, ext: String,
                          family: FileFamily, insideReclaimable: Bool) -> District {
        if insideReclaimable || isReclaimable(name: name, isDirectory: isDirectory, ext: ext) {
            return .landfill
        }
        return zoned(family)
    }
}
